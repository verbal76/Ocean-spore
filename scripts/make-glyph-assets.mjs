// Generates src/desktop/glyphAssets.web.ts (a static require table Metro can bundle)
// from assets/glyphs/manifest.json. The table lives in a .web.ts file, so the Android
// bundle never includes a single glyph. `--check` fails if the file is out of date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const manifest = JSON.parse(readFileSync('assets/glyphs/manifest.json', 'utf8'));
const OUT = 'src/desktop/glyphAssets.web.ts';

const keys = manifest.files.map((f) => f.file.replace(/\.png$/, '')).sort();
for (const k of keys) {
  if (!existsSync(`assets/glyphs/${k}.png`)) { console.error(`missing glyph file: assets/glyphs/${k}.png`); process.exit(1); }
}
const body = `// AUTO-GENERATED by scripts/make-glyph-assets.mjs from assets/glyphs/manifest.json. Do not edit.
// Desktop target only (.web.ts): the Android bundle never includes these images.
// Licence: see assets/glyphs/LICENSE.md.
export const GLYPH_ASSETS: Record<string, number> = {
${keys.map((k) => `  '${k}': require('../../assets/glyphs/${k}.png'),`).join('\n')}
};
`;
if (process.argv.includes('--check')) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (have !== body) { console.error(`${OUT} is out of date: run node scripts/make-glyph-assets.mjs`); process.exit(1); }
  console.log(`glyph assets OK: ${keys.length} glyphs`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} (${keys.length} glyphs)`);
}
