// Generates docs/THIRD-PARTY-LICENSES.md from package.json + node_modules:
// every direct production dependency with its declared licence, plus a licence
// summary of the whole production tree. Re-run after dependency changes:
//   node scripts/make-notices.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const lic = (j) => (typeof j.license === 'object' ? j.license.type : j.license)
  || (Array.isArray(j.licenses) && j.licenses.map((x) => x.type).join(' OR ')) || (j.licenses && j.licenses.type) || 'UNKNOWN';

const rows = Object.keys(pkg.dependencies).sort().map((name) => {
  const j = JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8'));
  const repo = typeof j.repository === 'string' ? j.repository : j.repository?.url ?? '';
  return `| ${name} | ${j.version} | ${lic(j)} | ${repo.replace(/^git\+/, '').replace(/\.git$/, '')} |`;
});

const tree = {};
for (const [p, v] of Object.entries(lock.packages)) {
  if (!p || v.dev) continue;
  let l = v.license;
  if (!l && existsSync(`${p}/package.json`)) l = lic(JSON.parse(readFileSync(`${p}/package.json`, 'utf8')));
  l = (typeof l === 'object' ? l?.type : l) || 'UNKNOWN';
  tree[l] = (tree[l] || 0) + 1;
}
const summary = Object.entries(tree).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k}: ${n}`).join(', ');

writeFileSync('docs/THIRD-PARTY-LICENSES.md', `# Third-party software licences

GENERATED by \`scripts/make-notices.mjs\` (do not edit). Source of truth: each
package's own \`package.json\` / LICENSE in the installed tree. Declared licences
are **identified, not independently verified**.

## Direct production dependencies

| Package | Version | Declared licence | Repository |
|---|---|---|---|
${rows.join('\n')}

## Whole production tree (lockfile, non-dev entries)

${summary}

Review notes: no GPL-only, AGPL or proprietary package was found. Dual-licensed
entries (\`node-forge\`: BSD-3-Clause OR GPL-2.0; \`type-fest\`: MIT OR CC0) are
usable under the permissive option. \`lightningcss\` (MPL-2.0, file-level copyleft)
is a bundler/web-tooling dependency, not part of the APK. \`requireg\` declares no
licence field (CLI tooling, not bundled). MIT/BSD/Apache licences require the
licence text and copyright notices to accompany distributed copies: a full
bundled-module notice file for public/store distribution still needs generating
with a bundler-aware tool at release time (owner/legal decision on presentation).
`);
console.log('wrote docs/THIRD-PARTY-LICENSES.md');
